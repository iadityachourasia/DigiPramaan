#!/usr/bin/env node
/**
 * generate-placeholders.mjs — branded placeholder images for the mock data.
 *
 * IMPLEMENTATION_GUIDE.md Step 4 forbids a grey box or a broken image anywhere, and
 * asks that a placeholder communicate brand and content intent: a low-opacity tint
 * of the brand primary, a centred relevant icon, and a correct aspect ratio.
 *
 * The tint is not typed in. It is read out of the installed ux4g-web-components
 * package's --ux4g-color-primary-600 at generation time, so this script cannot drift
 * from the token and no hex is hand-written into the repo.
 *
 * These only ever appear against mock data. BRD §11.7 is clear that this product
 * carries no decorative photography — every real image is a scan taken by an officer
 * or a citizen, so in production these are replaced by actual uploads rather than
 * kept as a fallback.
 *
 * Run: node scripts/generate-placeholders.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG_CSS = path.join(
  ROOT,
  "node_modules",
  "ux4g-web-components",
  "styles",
  "ux4g.css"
);
const OUT_DIR = path.join(ROOT, "public", "images", "placeholder");

if (!fs.existsSync(PKG_CSS)) {
  console.error("FAIL ux4g-web-components is not installed. Run `npm install` first.");
  process.exit(1);
}

const css = fs.readFileSync(PKG_CSS, "utf8");

function tokenValue(name) {
  const match = new RegExp(`${name}\\s*:\\s*([^;}]+)`).exec(css);
  if (!match) {
    console.error(`FAIL ${name} is not defined in the installed package.`);
    process.exit(1);
  }
  return match[1].trim();
}

const primary = tokenValue("--ux4g-color-primary-600");
const neutral0 = tokenValue("--ux4g-color-neutral-0");

/**
 * Simple line glyphs rather than the UX4G Material Icons font. A standalone .svg
 * loaded through an <img> cannot rely on a webfont being available, so these are
 * drawn as paths in the same outline style BRD §11.6 specifies.
 */
const GLYPHS = {
  "packaged-food":
    "M24 14h32l4 10v34a4 4 0 0 1-4 4H24a4 4 0 0 1-4-4V24Zm-4 10h40M32 34h16",
  beverages:
    "M30 12h20l-2 14a10 10 0 0 1 6 9v29a4 4 0 0 1-4 4H30a4 4 0 0 1-4-4V35a10 10 0 0 1 6-9Zm-4 24h28",
  "personal-care":
    "M32 12h16v8h-16Zm-4 8h24a6 6 0 0 1 6 6v36a4 4 0 0 1-4 4H26a4 4 0 0 1-4-4V26a6 6 0 0 1 6-6Zm2 18h20",
  "household-cleaning":
    "M34 10h12v10h-12Zm-6 10h24a6 6 0 0 1 6 6v38a4 4 0 0 1-4 4H26a4 4 0 0 1-4-4V26a6 6 0 0 1 6-6Zm2 20h20v14H30Z",
  pharmaceuticals:
    "M28 16h24a6 6 0 0 1 6 6v40a6 6 0 0 1-6 6H28a6 6 0 0 1-6-6V22a6 6 0 0 1 6-6Zm12 12v20m-10-10h20",
  "textiles-and-garments":
    "M30 12l10 6 10-6 12 8-6 10-4-2v36H28V28l-4 2-6-10Z",
  "electronics-and-appliances":
    "M18 18h44v30H18Zm10 38h24m-12-8v8M28 28h24v10H28Z",
  other: "M22 18h36v44H22Zm8 12h20m-20 10h20m-20 10h12",
  evidence:
    "M20 24h10l4-6h12l4 6h10a4 4 0 0 1 4 4v30a4 4 0 0 1-4 4H20a4 4 0 0 1-4-4V28a4 4 0 0 1 4-4Zm20 8a11 11 0 1 1 0 22 11 11 0 0 1 0-22Z",
  "ecommerce-listing":
    "M16 20h8l6 30h30l6-22H28M34 62a4 4 0 1 0 8 0 4 4 0 0 0-8 0Zm18 0a4 4 0 1 0 8 0 4 4 0 0 0-8 0Z",
};

/** 4:3, the aspect ratio a phone camera produces for a label photo. */
const WIDTH = 320;
const HEIGHT = 240;

fs.mkdirSync(OUT_DIR, { recursive: true });

for (const [name, glyph] of Object.entries(GLYPHS)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}" role="img" aria-hidden="true">
  <!-- Generated by scripts/generate-placeholders.mjs from --ux4g-color-primary-600. Do not hand-edit. -->
  <rect width="${WIDTH}" height="${HEIGHT}" fill="${neutral0}"/>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="${primary}" opacity="0.08"/>
  <g transform="translate(${WIDTH / 2 - 40} ${HEIGHT / 2 - 40})" fill="none" stroke="${primary}" stroke-opacity="0.55" stroke-width="3" stroke-linecap="round" stroke-linejoin="round">
    <path d="${glyph}"/>
  </g>
</svg>
`;
  fs.writeFileSync(path.join(OUT_DIR, `${name}.svg`), svg, "utf8");
}

console.log(
  `OK   wrote ${Object.keys(GLYPHS).length} placeholders to public/images/placeholder/ ` +
    `(tint from --ux4g-color-primary-600 = ${primary})`
);
